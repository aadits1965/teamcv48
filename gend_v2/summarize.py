"""Aggregate eval output over seeds -> results/summary.md (all numbers in README / report come from here).

  python -m gend_v2.summarize --eval results/eval_final --out results/summary.md
"""
import argparse
import ast
import json
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

SETS = ["FF++ (4 seen)", "FaceShifter (unseen gen.)", "DFD (cross-dataset)"]
ARMS = [("baseline", "Baseline (GenD, our run)"), ("pdc", "M1 PDC (selected)"), ("vrex", "M2 V-REx*"),
        ("m3", "M3 LN-SWA"), ("patch", "M4 patch pooling")]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--eval", default="results/eval_final")
    ap.add_argument("--out", default="results/summary.md")
    a = ap.parse_args()
    ev = Path(a.eval)
    r = pd.read_csv(ev / "results_test.csv")
    for c in ("auc_ci", "d_ci"):
        r[c] = r[c].apply(ast.literal_eval)
    get = lambda m, s, k: float(r[(r.model == m) & (r.testset == s)][k].iloc[0])
    L = ["# Results summary (video level; generated by `gend_v2/summarize.py`)\n",
         "Selection on validation (frozen before test): " + json.dumps(json.load(open(ev / "selection.json"))) + "\n",
         "## Main table: AUC mean ± sd over seeds 0,1,2; ΔAUC vs same-seed baseline; seeds whose paired-bootstrap 95% CI "
         "excludes 0 (+ above / − below); one-sample t-test of the 3 seed deltas (df = 2)\n",
         "| Method | " + " | ".join(SETS) + " |", "|---|" + "---|" * len(SETS)]
    for arm, label in ARMS:
        cells = []
        for s in SETS:
            ms = [f"{arm}_s{k}" for k in range(3)]
            au = np.array([get(m, s, "auc") for m in ms])
            if arm == "baseline":
                cells.append(f"{au.mean():.3f} ± {au.std(ddof=1):.3f}")
                continue
            d = np.array([get(m, s, "d_auc") for m in ms])
            up = sum(r[(r.model == m) & (r.testset == s)].d_ci.iloc[0][0] > 0 for m in ms)
            dn = sum(r[(r.model == m) & (r.testset == s)].d_ci.iloc[0][1] < 0 for m in ms)
            p = stats.ttest_1samp(d, 0).pvalue
            cells.append(f"{au.mean():.3f} ± {au.std(ddof=1):.3f} (Δ {d.mean():+.3f}; +{up}/−{dn}; p={p:.3f})")
        L.append(f"| {label} | " + " | ".join(cells) + " |")
    L.append("\n*V-REx evaluated at its best validated checkpoint after penalty activation (rule added after seeing seed-0 logs).\n")
    L += ["## Controls and reference (single runs; ΔAUC [95% CI] vs same-seed baseline)\n",
          "| Run | " + " | ".join(SETS) + " |", "|---|" + "---|" * len(SETS)]
    for m in ["pdc_shuffled_s0", "pdc_shuffled_s1", "pdc_lam0.1_s0", "pdc_s0", "pdc_lam2.0_s0",
              "vrex_s0_preact", "vrex_s1_preact", "official_GenD_CLIP_L14"]:
        cells = []
        for s in SETS:
            row = r[(r.model == m) & (r.testset == s)].iloc[0]
            cells.append(f"{row.auc:.3f} (Δ {row.d_auc:+.3f} [{row.d_ci[0]:+.3f},{row.d_ci[1]:+.3f}])")
        L.append(f"| {m} | " + " | ".join(cells) + " |")
    L.append("\n(`official_GenD_CLIP_L14` Δ is vs baseline_s0; it is trained on the full FF++ train split with 32 frames.)\n")
    pm = r[r.testset.str.startswith("FF++/")].pivot(index="model", columns="testset", values="auc")
    L += ["## FF++ per-manipulation AUC (mean over seeds)\n", "| Method | " + " | ".join(c[5:] for c in pm.columns) + " |",
          "|---|" + "---|" * len(pm.columns)]
    for arm, label in ARMS:
        vals = pm.loc[[f"{arm}_s{k}" for k in range(3)]].mean()
        L.append(f"| {label} | " + " | ".join(f"{v:.3f}" for v in vals) + " |")
    L.append(f"| official GenD | " + " | ".join(f"{v:.3f}" for v in pm.loc["official_GenD_CLIP_L14"]) + " |")
    dg = json.load(open(ev / "diagnostics.json"))
    L += ["\n## Mechanism: mean cos(fake−real direction, mean seen-method direction) on test pairs (mean over seeds)\n",
          "| Method | DF | F2F | FS | NT | FaceShifter (unseen) |", "|---|---|---|---|---|---|"]
    for arm, label in ARMS:
        cs = np.array([[dg[f"{arm}_s{k}"]["pair_direction_cos"][m] for m in
                        ["Deepfakes", "Face2Face", "FaceSwap", "NeuralTextures", "FaceShifter"]] for k in range(3)]).mean(0)
        L.append(f"| {label} | " + " | ".join(f"{c:.3f}" for c in cs) + " |")
    for m in ["pdc_shuffled_s0", "pdc_shuffled_s1", "pdc_lam0.1_s0", "pdc_lam2.0_s0"]:
        cs = [dg[m]["pair_direction_cos"][x] for x in ["Deepfakes", "Face2Face", "FaceSwap", "NeuralTextures", "FaceShifter"]]
        L.append(f"| {m} | " + " | ".join(f"{c:.3f}" for c in cs) + " |")
    Path(a.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
